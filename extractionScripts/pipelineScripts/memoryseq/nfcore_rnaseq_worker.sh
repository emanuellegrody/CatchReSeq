#!/bin/bash
# nfcore_rnaseq_worker.sh
# Runs nf-core/rnaseq over the LD002 clone libraries to produce the
# gene-level TPM matrix that memoryseq_heritable_genes.R reads.
#
# This is the only stage in the repository driven by Nextflow rather than by
# sbatch directly: nf-core submits its own jobs, so this script runs on a login
# node (or inside a long-lived allocation) and the cluster profile below hands
# each process to SLURM.
#
# Required env vars, set by submissionScripts/<Figure>/*.sh:
#   SAMPLE_SHEET      nf-core sample sheet. fastq_1/fastq_2 may be bare file
#                     names relative to FASTQ_ROOT; this script expands them.
#   FASTQ_ROOT        dir the sample sheet's relative FASTQ paths resolve against
#   OUTPUT_DIR        nf-core --outdir
#   GTF               gene annotation
#   FASTA             genome FASTA
#
# Optional:
#   NFCORE_VERSION    pipeline revision (default 3.17.0)
#   NEXTFLOW_ENV      conda env holding nextflow (default "nextflow")
#   SLURM_ACCOUNT     account for the processes nf-core submits (default b1042)
#   SLURM_PARTITION   partition for those processes (default genomics)
#   WORK_DIR          where the expanded sheet, config and Nextflow work tree go
#                     (default <OUTPUT_DIR>/../nfcore_work)

set -euo pipefail

require_env() {
    local name="$1"
    if [ -z "${!name:-}" ]; then
        echo "Error: required environment variable not set: ${name}" >&2
        exit 1
    fi
}

for required in SAMPLE_SHEET FASTQ_ROOT OUTPUT_DIR GTF FASTA; do
    require_env "$required"
done

NFCORE_VERSION="${NFCORE_VERSION:-3.17.0}"
NEXTFLOW_ENV="${NEXTFLOW_ENV:-nextflow}"
SLURM_ACCOUNT="${SLURM_ACCOUNT:-b1042}"
SLURM_PARTITION="${SLURM_PARTITION:-genomics}"
WORK_DIR="${WORK_DIR:-${OUTPUT_DIR%/}/../nfcore_work}"

for input in "$SAMPLE_SHEET" "$GTF" "$FASTA"; do
    [ -f "$input" ] || { echo "Error: file not found: ${input}" >&2; exit 1; }
done
[ -d "$FASTQ_ROOT" ] || { echo "Error: FASTQ_ROOT is not a directory: ${FASTQ_ROOT}" >&2; exit 1; }

mkdir -p "$WORK_DIR" "$OUTPUT_DIR"

# The committed sheet carries bare file names so it survives the data moving,
# and nf-core needs absolute paths, so the two are joined here. A field that is
# already absolute is passed through, which lets a sheet written the nf-core way
# be used unchanged.
EXPANDED_SHEET="${WORK_DIR}/nfcore_samplesheet_expanded.csv"
FASTQ_ROOT="${FASTQ_ROOT%/}" awk -F, -v OFS=, '
    NR == 1 { print; next }
    NF == 0 { next }
    {
        for (field = 2; field <= 3; field++) {
            if ($field != "" && $field !~ /^\//) {
                $field = ENVIRON["FASTQ_ROOT"] "/" $field
            }
        }
        print
    }
' "$SAMPLE_SHEET" > "$EXPANDED_SHEET"

missing=0
while IFS=, read -r sample fastq_1 fastq_2 strandedness; do
    [ "$sample" = "sample" ] && continue
    for fastq in "$fastq_1" "$fastq_2"; do
        [ -n "$fastq" ] || continue
        if [ ! -f "$fastq" ]; then
            echo "Missing FASTQ: ${fastq}" >&2
            missing=$((missing + 1))
        fi
    done
done < "$EXPANDED_SHEET"
if [ "$missing" -gt 0 ]; then
    echo "Error: ${missing} FASTQ file(s) named by ${SAMPLE_SHEET} are not on disk." >&2
    echo "       Point FASTQ_ROOT at the LD002 reads, or restore them first." >&2
    exit 1
fi

# Nextflow reads its parameters from a config file rather than the command line
# here, so the config is generated from the environment instead of being
# committed with paths baked in.
GENERATED_CONFIG="${WORK_DIR}/rnaseq.config"
cat > "$GENERATED_CONFIG" <<CONFIG_EOF
// Generated by nfcore_rnaseq_worker.sh -- edits here are overwritten.
params {
   input  = '${EXPANDED_SHEET}'
   outdir = '${OUTPUT_DIR}'
   gtf    = '${GTF}'
   fasta  = '${FASTA}'
}
profiles {
   cluster {
       process.executor = 'slurm'
       executor.queueSize = 10
       process.cpu = '20'
       process.memory = '100 GB'
       process.queue = '${SLURM_PARTITION}'
       process.clusterOptions = '--account=${SLURM_ACCOUNT}'
   }
   singularity {
       singularity.enabled = true
       singularity.cacheDir = '${WORK_DIR}/.singularity_cache'
   }
}
CONFIG_EOF

module purge
module load anaconda3
module load singularity/3.8.1
source activate "$NEXTFLOW_ENV"

cd "$WORK_DIR"
nextflow run nf-core/rnaseq \
    -r "$NFCORE_VERSION" \
    -c "$GENERATED_CONFIG" \
    -profile singularity,cluster \
    -resume

echo "nf-core/rnaseq ${NFCORE_VERSION} finished."
echo "Gene TPM matrix: ${OUTPUT_DIR%/}/star_salmon/salmon.merged.gene_tpm.tsv"
