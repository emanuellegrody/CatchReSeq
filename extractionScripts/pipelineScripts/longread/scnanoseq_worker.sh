#!/bin/bash
# scnanoseq_worker.sh
# Runs nf-core/scnanoseq over the EGS007 long-read libraries to produce the
# barcode-tagged, deduplicated BAM and the IsoQuant gene and transcript counts
# that Figure2 reads.
#
# Like nfcore_rnaseq_worker.sh this is driven by Nextflow rather than sbatch:
# nf-core submits its own jobs, so this script runs on a login node (or inside
# a long-lived allocation) and the cluster profile below hands each process to
# SLURM.
#
# Required env vars, set by submissionScripts/<Figure>/*.sh:
#   SAMPLE_SHEET      scnanoseq sample sheet, columns sample,fastq,cell_count.
#                     `fastq` may be a bare file name relative to FASTQ_ROOT;
#                     this script expands it.
#   FASTQ_ROOT        dir the sample sheet's relative FASTQ paths resolve against
#   OUTPUT_DIR        nf-core --outdir
#   GTF               gene annotation for the viral contig
#   FASTA             genome FASTA for the viral contig. The long-read arm uses
#                     the full-length 10279bp mac239 rather than the 9602bp
#                     cellranger build, which drops the 5' LTR U3 and the 3' U5
#                     so short reads cannot multimap between the two LTRs.
#
# Optional:
#   NFCORE_VERSION    pipeline revision (default 1.0.0)
#   NEXTFLOW_ENV      conda env holding nextflow (default "nextflow")
#   SLURM_ACCOUNT     account for the processes nf-core submits (default b1042)
#   SLURM_PARTITION   partition for those processes (default genomics)
#   WORK_DIR          where the expanded sheet, config and Nextflow work tree go
#                     (default <OUTPUT_DIR>/../nfcore_work)
#   BARCODE_FORMAT    10x chemistry (default 10X_3v3)
#   KMER_SIZE         minimap2 -k (default 14)
#   MIN_Q_SCORE       NanoFilt quality floor (default 10)
#   MIN_LENGTH        NanoFilt length floor (default 1)
#   RETAIN_INTRONS    pass intronic reads to IsoQuant (default true)

set -euo pipefail

require_env() {
    local name="$1"
    if [ -z "${!name:-}" ]; then
        echo "Error: required environment variable not set: ${name}" >&2
        exit 1
    fi
}

for required in SAMPLE_SHEET FASTQ_ROOT OUTPUT_DIR GTF FASTA; do
    require_env "$required"
done

NFCORE_VERSION="${NFCORE_VERSION:-1.0.0}"
NEXTFLOW_ENV="${NEXTFLOW_ENV:-nextflow}"
SLURM_ACCOUNT="${SLURM_ACCOUNT:-b1042}"
SLURM_PARTITION="${SLURM_PARTITION:-genomics}"
WORK_DIR="${WORK_DIR:-${OUTPUT_DIR%/}/../nfcore_work}"
BARCODE_FORMAT="${BARCODE_FORMAT:-10X_3v3}"
KMER_SIZE="${KMER_SIZE:-14}"
MIN_Q_SCORE="${MIN_Q_SCORE:-10}"
MIN_LENGTH="${MIN_LENGTH:-1}"
RETAIN_INTRONS="${RETAIN_INTRONS:-true}"

for input in "$SAMPLE_SHEET" "$GTF" "$FASTA"; do
    [ -f "$input" ] || { echo "Error: file not found: ${input}" >&2; exit 1; }
done
[ -d "$FASTQ_ROOT" ] || { echo "Error: FASTQ_ROOT is not a directory: ${FASTQ_ROOT}" >&2; exit 1; }

mkdir -p "$WORK_DIR" "$OUTPUT_DIR"

# The committed sheet carries bare file names so it survives the data moving,
# and nf-core needs absolute paths, so the two are joined here. A field that is
# already absolute is passed through, which lets a sheet written the nf-core way
# be used unchanged.
EXPANDED_SHEET="${WORK_DIR}/scnanoseq_samplesheet_expanded.csv"
FASTQ_ROOT="${FASTQ_ROOT%/}" awk -F, -v OFS=, '
    NR == 1 { print; next }
    NF == 0 { next }
    {
        if ($2 != "" && $2 !~ /^\//) {
            $2 = ENVIRON["FASTQ_ROOT"] "/" $2
        }
        print
    }
' "$SAMPLE_SHEET" > "$EXPANDED_SHEET"

missing=0
while IFS=, read -r sample fastq cell_count; do
    [ "$sample" = "sample" ] && continue
    [ -n "$fastq" ] || continue
    if [ ! -f "$fastq" ]; then
        echo "Missing FASTQ: ${fastq}" >&2
        missing=$((missing + 1))
    fi
done < "$EXPANDED_SHEET"
if [ "$missing" -gt 0 ]; then
    echo "Error: ${missing} FASTQ file(s) named by ${SAMPLE_SHEET} are not on disk." >&2
    echo "       Point FASTQ_ROOT at the EGS007 long reads." >&2
    exit 1
fi

# Nextflow reads its parameters from a config file rather than the command line
# here, so the config is generated from the environment instead of being
# committed with paths baked in.
GENERATED_CONFIG="${WORK_DIR}/scnanoseq.config"
cat > "$GENERATED_CONFIG" <<CONFIG_EOF
// Generated by scnanoseq_worker.sh -- edits here are overwritten.
params {
   input           = '${EXPANDED_SHEET}'
   outdir          = '${OUTPUT_DIR}'
   gtf             = '${GTF}'
   fasta           = '${FASTA}'
   barcode_format  = '${BARCODE_FORMAT}'
   kmer_size       = ${KMER_SIZE}
   min_q_score     = ${MIN_Q_SCORE}
   min_length      = ${MIN_LENGTH}
   retain_introns  = ${RETAIN_INTRONS}
   igenomes_ignore = true
}
profiles {
   cluster {
       process.executor = 'slurm'
       executor.queueSize = 10
       process.cpu = '20'
       process.memory = '100 GB'
       process.queue = '${SLURM_PARTITION}'
       process.clusterOptions = '--account=${SLURM_ACCOUNT}\n#SBATCH --time=48:00:00'
   }
   singularity {
       singularity.enabled = true
       singularity.cacheDir = '${WORK_DIR}/.singularity_cache'
   }
}
CONFIG_EOF

module purge
module load anaconda3
module load singularity/3.8.1
source activate "$NEXTFLOW_ENV"

cd "$WORK_DIR"
nextflow run nf-core/scnanoseq \
    -r "$NFCORE_VERSION" \
    -c "$GENERATED_CONFIG" \
    -profile singularity,cluster \
    -resume

echo "nf-core/scnanoseq ${NFCORE_VERSION} finished."
echo "Deduplicated BAM:   ${OUTPUT_DIR%/}/<sample>/bam/dedup/<sample>.dedup.sorted.bam"
echo "IsoQuant counts:    ${OUTPUT_DIR%/}/<sample>/isoquant/<sample>.{gene,transcript}_counts.tsv"
